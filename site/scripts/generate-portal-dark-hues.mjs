// Generates src/styles/portal-dark-hues.css — the coloured half of the portal's dark
// theme — from Tailwind's own palette, so the values never drift from the utilities.
// Run from site/:  node scripts/generate-portal-dark-hues.mjs
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

const themeCss = process.argv[2] ?? 'node_modules/tailwindcss/theme.css'
const outFile = process.argv[3] ?? 'src/styles/portal-dark-hues.css'
const theme = readFileSync(themeCss, 'utf8')
const val = (name) => {
  const m = theme.match(new RegExp(`--color-${name}:\\s*([^;]+);`))
  if (!m) throw new Error(`missing --color-${name} in ${themeCss}`)
  return m[1].trim()
}

const HUES = ['red', 'orange', 'amber', 'yellow', 'lime', 'green', 'emerald', 'teal', 'cyan',
  'sky', 'blue', 'indigo', 'violet', 'purple', 'fuchsia', 'pink', 'rose']
// Pale tints become a translucent wash of the hue's 500, so badges and alert
// panels read as tinted dark surfaces instead of glowing light pills.
const TINTS = { 50: 14, 100: 20, 200: 30 }
// Deep text shades are lifted to their light counterparts to stay readable.
const LIFT = { 600: 400, 700: 300, 800: 200, 900: 100, 950: 50 }

const NEUTRALS = { gray: 950, slate: 900, neutral: 900 }
const NEUTRAL_SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950]

// Element-level rules skip anything inside a light island (a certificate sheet).
const NOT_LIGHT = ':not(.cares-light-surface *)'
const esc = (cls) => cls.replace(/:/g, '\\:').replace(/\//g, '\\/')
const out = []

out.push(`/* GENERATED by scripts/generate-portal-dark-hues.mjs — regenerate, don't hand-edit.

   Portal dark theme, hue layer. Every Tailwind colour utility reads a --color-*
   variable, so dark mode redefines variables and never overrides utility classes
   (an unlayered class override would beat hover: variants and break them).
   1. Pale tints (50/100/200) are redefined on <html> as translucent washes.
   2. Deep shades (600-950) are lifted only on elements that use them as TEXT, by
      redefining the variable on that element; an element painting the same shade
      as a background gets the original value back.
   3. .cares-light-surface is a light island (a certificate sheet): inside it every
      variable is restored and the element-level rules above do not apply. */
`)

out.push('html.dark {')
for (const h of HUES) {
  const base = val(`${h}-500`)
  for (const [shade, pct] of Object.entries(TINTS)) {
    out.push(`  --color-${h}-${shade}: color-mix(in oklab, ${base} ${pct}%, transparent);`)
  }
}
out.push('}\n')

// Pale text keeps its real value (e.g. text-emerald-100 on a bg-emerald-700 banner).
for (const h of HUES) {
  const sels = []
  for (const shade of Object.keys(TINTS)) {
    for (const p of ['', 'hover:', 'group-hover:']) {
      sels.push(`html.dark .${esc(`${p}text-${h}-${shade}`)}${NOT_LIGHT}`)
    }
  }
  out.push(`${sels.join(',\n')} {`)
  for (const shade of Object.keys(TINTS)) out.push(`  --color-${h}-${shade}: ${val(`${h}-${shade}`)};`)
  out.push('}\n')
}

for (const h of HUES) {
  for (const [shade, to] of Object.entries(LIFT)) {
    const sels = ['', 'hover:', 'group-hover:', 'focus:'].map(
      (p) => `html.dark .${esc(`${p}text-${h}-${shade}`)}${NOT_LIGHT}`,
    )
    out.push(`${sels.join(', ')} { --color-${h}-${shade}: ${val(`${h}-${to}`)}; }`)
  }
}
out.push('')
for (const h of HUES) {
  for (const shade of Object.keys(LIFT)) {
    const sels = ['', 'hover:'].map((p) => `html.dark .${esc(`${p}bg-${h}-${shade}`)}${NOT_LIGHT}`)
    out.push(`${sels.join(', ')} { --color-${h}-${shade}: ${val(`${h}-${shade}`)}; }`)
  }
}
out.push('')

// Light islands: printed artefacts (certificate sheets) keep the light palette in
// dark mode. The CARES tokens are restored by hand in portal-dark.css.
out.push('html.dark .cares-light-surface {')
out.push('  color-scheme: light;')
out.push('  --color-white: #fff;')
for (const [n, top] of Object.entries(NEUTRALS)) {
  for (const s of NEUTRAL_SHADES.filter((s) => s <= top)) out.push(`  --color-${n}-${s}: ${val(`${n}-${s}`)};`)
}
for (const h of HUES) {
  for (const shade of Object.keys(TINTS)) out.push(`  --color-${h}-${shade}: ${val(`${h}-${shade}`)};`)
}
out.push('}')
out.push('')

mkdirSync(dirname(outFile), { recursive: true })
writeFileSync(outFile, out.join('\n'))
console.log(`wrote ${outFile}`)
